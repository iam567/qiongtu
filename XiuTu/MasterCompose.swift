    /// 换成"按大师的构图重新取景"。找不到这位大师或指令不是标准格式时返回 nil。
    static func prompt(_ base: String, title: String, hasPerson: Bool) -> String? {
        guard base.contains(keepTail),
              let layout = hasPerson ? layouts[title] : sceneLayouts[title] else { return nil }
        let tail: String
        if hasPerson {
            tail = "构图也按这种风格重新安排：\(layout)。可以重新取景、改变景别、机位和裁切，场景缺的部分按原场景合理补全；" +
                "但必须还是同一个人、同一个地方：人物长相、发型和服装都不变，不要添加原场景里没有的人和物，画面里不要画出网格、辅助线或取景框。画面比例不变，结果是一张真实的照片。"
        } else {
            tail = "构图也按这种风格重新安排：\(layout)。可以重新取景、改变景别、机位和裁切，场景缺的部分按原场景合理补全；" +
                "但必须还是同一个地方，陈设和物件都来自原场景。原照片里没有人，结果里也不能出现任何人、人影或人体的一部分——" +
                "上面说到的人像、肤色只是在讲影调，不要因此加人；也不要添加原场景里没有的东西，画面里不要画出网格、辅助线或取景框。画面比例不变，结果是一张真实的照片。"
        }
        return base.replacingOccurrences(of: keepTail, with: tail)
    }

    /// 照片里有没有人：认出人体或者人脸都算有；人很小时切块放大再找一遍。
    /// 不用人像分割判断——它在岩石、水流这类纹理上会误报出一大片"人"。
    static func hasPerson(in image: CGImage) -> Bool {
        let human = VNDetectHumanRectanglesRequest()
        human.upperBodyOnly = false
        let face = VNDetectFaceRectanglesRequest()
        try? VNImageRequestHandler(cgImage: image, options: [:]).perform([human, face])
        let people = (human.results ?? []).filter { $0.confidence >= 0.5 }
        return !people.isEmpty || !(face.results ?? []).isEmpty || !FaceFinder.deep(image, thorough: true).isEmpty
    }
