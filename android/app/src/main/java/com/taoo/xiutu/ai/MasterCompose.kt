    /** 大师指令里"构图保持原样"的那句尾巴。 */
    private const val KEEP_TAIL = "只调整光线、色彩、反差和影调；画面内容、人物长相、姿势、服装和构图都保持原样，结果仍是一张真实的照片。"

    /** 换成"按大师的构图重新取景"。找不到这位大师或指令不是标准格式时返回 null。 */
    fun prompt(base: String, title: String, hasPerson: Boolean): String? {
        val layout = (if (hasPerson) layouts[title] else sceneLayouts[title]) ?: return null
        if (!base.contains(KEEP_TAIL)) return null
        val tail = if (hasPerson) {
            "构图也按这种风格重新安排：$layout。可以重新取景、改变景别、机位和裁切，场景缺的部分按原场景合理补全；" +
                "但必须还是同一个人、同一个地方：人物长相、发型和服装都不变，不要添加原场景里没有的人和物，画面里不要画出网格、辅助线或取景框。画面比例不变，结果是一张真实的照片。"
        } else {
            "构图也按这种风格重新安排：$layout。可以重新取景、改变景别、机位和裁切，场景缺的部分按原场景合理补全；" +
                "但必须还是同一个地方，陈设和物件都来自原场景。原照片里没有人，结果里也不能出现任何人、人影或人体的一部分——" +
                "上面说到的人像、肤色只是在讲影调，不要因此加人；也不要添加原场景里没有的东西，画面里不要画出网格、辅助线或取景框。画面比例不变，结果是一张真实的照片。"
        }
        return base.replace(KEEP_TAIL, tail)
    }

    /** 照片里有没有人：认出人脸或者人体姿态都算有；人很小时切块放大再找一遍。 */
    fun hasPerson(image: Bitmap): Boolean =
        runCatching { FaceDetector.direct(image).isNotEmpty() }.getOrDefault(false) ||
            runCatching { ShapeBodyDetector.detect(image).isNotEmpty() }.getOrDefault(false) ||
            runCatching { FaceFinder.deep(image, thorough = true).isNotEmpty() }.getOrDefault(false)
}
