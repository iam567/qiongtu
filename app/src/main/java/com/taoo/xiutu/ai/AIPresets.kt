/** AI 面板里的一条快捷指令。 */
data class AIPreset(
    val title: String,
    /** 按钮上的图标。 */
    val symbol: String = "sparkles",
    val prompt: String,
    /** 没涂抹时自动找到人脸，只把头部这一块发给 AI（修跑焦）。 */
    val faceCrop: Boolean = false,
    /** 美发：没涂抹时自动把头和头发这一块发给 AI。 */
    val hairCrop: Boolean = false,
    /** 只采用 AI 的光影和颜色、细节保留原图。 */
    val toneOnly: Boolean = false,
    /** 按钮显示成这个颜色的色块（染发用），0xRRGGBB。 */
    val tint: Int? = null,
    /** 只改身体的这一块：结果只在这一块里采用。 */
    val part: BodyPart? = null,
)

object AIIntent {
    /** 修跑焦：强调这是"还原"不是"重画"，五官的形状和位置一点都不能变。 */
    const val REFOCUS_PROMPT =
        "This is a crop from a photo where the camera focused on the background, so the person is slightly out of focus. " +
            "Restore sharp focus on the person: crisp eyes and eyelashes, individual hair strands, realistic skin texture with pores, clear fabric texture. " +
            "This is a restoration, not a redraw. Every facial feature must keep exactly the same shape, size, position and proportions as in the input: " +
            "the same eye shape and spacing, the same nose, lips, eyebrows, jawline, face width, the same expression and gaze direction. " +
            "Do not beautify, do not change makeup, skin tone, lighting, colors or hairstyle. It must be unmistakably the same individual. " +
            "Keep the exact same framing and position of everything so the result can be overlaid on the original. Photorealistic."

    /** 修手抖：去掉拍摄时相机晃动造成的拖影和重影。 */
    const val DESHAKE_PROMPT =
        "这张照片拍的时候相机晃了，画面有手抖造成的运动模糊、拖影和重影。把手抖去掉：" +
            "把重影合回一个清晰的轮廓，恢复锐利的边缘和真实的细节（文字、车牌、灯、发丝、纹理都要清楚），就像用安全快门、稳稳拍下的同一张照片。" +
            "这是还原，不是重画：构图、视角、所有东西的形状大小和位置、颜色、光线都和原图一致，结果要能和原图逐像素对齐叠在一起。" +
            "不要磨皮美化，不要改人物长相，不要加任何新东西。真实的照片质感。"

    /** 修手：涂住画错的手。 */
    const val HAND_PROMPT =
        "涂抹区域里的手画错了（手指数量、长短、关节或形状不对）。把涂抹区域里的手改成一只自然、解剖正确的手：五根手指，长短粗细和关节正确，指甲自然，" +
            "手的大小、朝向、姿势和手腕、手臂衔接得上；肤色、光线方向、明暗和清晰度与手臂一致。原来画坏的那只手要完全去掉，不能留下轮廓、残影、重影或半透明的痕迹，手旁边露出来的背景按周围自然补全。" +
            "区域外、袖子、首饰和背景都不变，结果是一张真实的照片。"

    /**
     * 指令是不是"把涂抹的东西去掉/换掉"这一类。
     * 这一类才把涂抹区域当蒙版发出去；其他指令是在原有内容上修改，AI 必须看到原图，所以不发蒙版。
     */
    fun replacesContent(prompt: String): Boolean {
        val p = prompt.lowercase()
        return listOf("去掉", "消除", "删除", "移除", "抹掉", "擦掉", "去除", "换成", "替换", "remove", "erase", "delete", "replace")
            .any { p.contains(it) }
    }

    /** 自己写的指令是不是在换衣服：是的话背景一律用原图。 */
    fun changesClothes(prompt: String): Boolean {
        val wear = listOf("衣服", "裙", "礼服", "婚纱", "西装", "外套", "旗袍", "和服", "汉服", "上衣", "裤", "大衣", "衬衫", "制服", "穿搭", "换装", "穿着")
        val verbs = listOf("换", "改成", "变成", "穿上", "换装", "穿成")
        return wear.any { it in prompt } && verbs.any { it in prompt }
    }
}

enum class AIPresetGroup(val title: String, val symbol: String) {
    FIX("修复", "wand.and.stars"),
    LIGHT("光线", "lightbulb"),
    REMOVE("消除", "eraser"),
    OUTFIT("换衣服", "tshirt"),
    COMPOSE("构图", "crop"),
    MASTER("大师", "camera.aperture"),
    CAMERA("相机", "camera"),
    CREATIVE("创意", "theatermasks"),
    BODY("AI 美体", "figure.stand"),
    HAIR_STYLE("发型", "scissors"),
    HAIR_COLOR("染发", "paintpalette"),
    HAIR_CARE("发质发量", "wand.and.stars");

    val isHair get() = this in hairGroups

    /** 主菜单里的名字（面板里的分段标签用更短的 title）。 */
    val menuTitle get() = when (this) {
        CAMERA -> "相机质感"
        CREATIVE -> "创意玩法"
        else -> title
    }

    /** 这一组的按钮用图片（小图是本机模拟的大致色调）。 */
    val usesTonePreview get() = this == MASTER || this == CAMERA || this == LIGHT || this == CREATIVE

    /** 美体和美发三组按女 / 男开关给不同的一套。 */
    val presets: List<AIPreset>
        get() {
            if (GenderSetting.isMale) when (this) {
                BODY -> return MalePresets.body
                HAIR_STYLE -> return MalePresets.hairStyles
                HAIR_COLOR -> return MalePresets.hairColors
                HAIR_CARE -> return MalePresets.hairCare
                else -> {}
            }
            return PRESETS.getValue(this)
        }

    companion object {
        /** 美发的三组。 */
        val hairGroups = listOf(HAIR_STYLE, HAIR_COLOR, HAIR_CARE)

        /** AI 修图面板里的几组；AI 美体单独放在"美体"里。 */
        val editGroups = listOf(FIX, LIGHT, REMOVE, OUTFIT, COMPOSE, MASTER, CAMERA, CREATIVE)
    }
}

/** AI 构图时输出成什么画幅。 */
enum class AIReframe(val title: String, val symbol: String) {
    ORIGINAL("原比例", "aspectratio"),
    PORTRAIT("竖幅", "rectangle.portrait"),
    LANDSCAPE("横幅", "rectangle"),
    SQUARE("方形", "square");

    /** 输出尺寸（各家都支持的标准尺寸）。 */
    val size: Pair<Int, Int>?
        get() = when (this) {
            ORIGINAL -> null
            PORTRAIT -> 1024 to 1536
            LANDSCAPE -> 1536 to 1024
            SQUARE -> 1024 to 1024
        }

    /** 写进指令里的说法。 */
    val instruction: String
        get() = when (this) {
            ORIGINAL -> ""
            PORTRAIT -> "竖幅（2:3，竖着拿相机拍的）"
            LANDSCAPE -> "横幅（3:2，横着拿相机拍的）"
            SQUARE -> "方形（1:1）"
        }
}

